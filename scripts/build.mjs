// Build step (runs locally and on Vercel):
//  1. public/config.js      <- SUPABASE_URL + SUPABASE_ANON_KEY from env (or .env locally)
//  2. public/vendor/supabase.js <- Supabase client copied from node_modules (so it works offline)
//  3. public/version.js     <- build id used by the service worker cache
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'public');

// Load .env for local builds (Vercel injects env vars directly).
const envFile = join(root, '.env');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const url = (process.env.SUPABASE_URL || '').trim();
const key = (process.env.SUPABASE_ANON_KEY || '').trim();
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/i.test(url) && !/^https?:\/\/(localhost|127\.0\.0\.1)/.test(url)) {
  console.warn(`! SUPABASE_URL looks unusual: ${url}`);
}

writeFileSync(join(pub, 'config.js'),
  `// Generated by scripts/build.mjs. Do not edit.\nwindow.PXM_CONFIG = ${JSON.stringify({ supabaseUrl: url.replace(/\/$/, ''), supabaseAnonKey: key })};\n`);

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@supabase/supabase-js/package.json'));
mkdirSync(join(pub, 'vendor'), { recursive: true });
copyFileSync(join(pkgDir, 'dist', 'umd', 'supabase.js'), join(pub, 'vendor', 'supabase.js'));
copyFileSync(require.resolve('qrcode-generator'), join(pub, 'vendor', 'qrcode.js'));

const version = process.env.VERCEL_GIT_COMMIT_SHA?.slice(0, 8) || Date.now().toString(36);
writeFileSync(join(pub, 'version.js'), `self.PXM_VERSION = ${JSON.stringify(version)};\n`);

console.log(url && key
  ? `✓ Built with cloud sync → ${url} (version ${version})`
  : `✓ Built in OFFLINE mode (no SUPABASE_URL / SUPABASE_ANON_KEY set) (version ${version})`);
